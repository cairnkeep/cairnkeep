import assert from 'node:assert/strict';
import { hardenPrivatePath } from '../dist/platform-security.js';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openTeamStore, teamDigest } from '../dist/team-store.js';
import { randomUUID } from 'node:crypto';
import { spawn } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';

process.env.CAIRN_TEAM = '1';
const base = mkdtempSync(join(tmpdir(), 'cairn-team-review-'));
hardenPrivatePath(base);
const store = await openTeamStore(join(base, 'team'), { create: true, organization: 'demo-org' });
const call = (token, operation, extra = {}, project = 'alpha') => store.execute(token, { organization: 'demo-org', project, operation, ...extra });
try {
  for (const project of ['alpha', 'beta']) await store.admin({ operation: 'project-create', project });
  const existingOperation = store.admin({ operation: 'project-create', project: 'gamma' });
  const concurrentOpen = openTeamStore(join(base, 'team'));
  await existingOperation;
  const otherConnection = await concurrentOpen;
  await otherConnection.close();
  for (const [subject, roles] of [['alice', ['reader', 'contributor', 'reviewer']], ['bob', ['reader', 'reviewer']], ['worker', ['contributor', 'reviewer']], ['auditor', ['auditor']], ['admin', ['maintainer']]]) {
    await store.admin({ operation: 'member-set', project: 'alpha', subject, roles });
  }
  const issue = async (subject, credential_class = 'human') => (await store.issue({ subject, credential_class, expires_at: new Date(Date.now() + 60000).toISOString() })).token;
  const alice = await issue('alice'), bob = await issue('bob'), worker = await issue('worker', 'workload'), auditor = await issue('auditor'), admin = await issue('admin');
  const value = 'Reviewed tunnel policy: use the approved gateway, never expose credentials.';
  const input = { request_id: randomUUID(), key: 'decisions/gateway', value, source_scope: 'selected-local', source_digest: teamDigest('selected source'), base_revision: null, expires_at: new Date(Date.now() + 60000).toISOString(), confirm: teamDigest(value) };
  await assert.rejects(call(alice, 'propose', { ...input, confirm: '0'.repeat(64) }), /invalid/);
  const proposal = await call(alice, 'propose', input);
  assert.equal(proposal.value, undefined, 'proposal acknowledgments do not repeat candidate content');
  assert.deepEqual(await call(bob, 'list'), [], 'unreviewed context is invisible');
  assert.deepEqual(await call(alice, 'propose', input), proposal, 'submission is idempotent');
  await assert.rejects(call(alice, 'propose', { ...input, value: 'changed', confirm: teamDigest('changed') }), /conflict/);
  const review = { proposal_id: proposal.id, confirm: proposal.digest, decision: 'approve' };
  await assert.rejects(call(alice, 'review', review), /denied/);
  await assert.rejects(call(worker, 'review', review), /denied/);
  await assert.rejects(call(admin, 'review', review), /denied/);
  await assert.rejects(call(bob, 'review', { ...review, confirm: '0'.repeat(64) }), /conflict/);
  const competing = await call(alice, 'propose', { ...input, request_id: randomUUID(), value: 'second candidate', confirm: teamDigest('second candidate') });
  const results = await Promise.allSettled([call(bob, 'review', review), call(bob, 'review', { ...review, proposal_id: competing.id, confirm: competing.digest })]);
  assert.equal(results.filter(x => x.status === 'fulfilled').length, 1, 'one competing base wins');
  const approved = await call(bob, 'read', { key: input.key });
  assert.equal(approved.value, value);
  assert.equal(approved.provenance.organization, 'demo-org');
  assert.equal(approved.provenance.project, 'alpha');
  assert.deepEqual(await call(bob, 'review', review), results[0].value, 'exact approval replay is idempotent');
  assert.equal((await call(bob, 'history', { key: input.key })).length, 1);
  assert.equal((await call(alice, 'search', { query: 'approved gateway' })).length, 1);
  await assert.rejects(call(auditor, 'read', { key: input.key }), /denied/);
  await assert.rejects(call(bob, 'read', { key: input.key }, 'beta'), /denied/);
  const stale = await call(alice, 'propose', { ...input, request_id: randomUUID(), base_revision: approved.provenance.revision_digest });
  await store.admin({ operation: 'member-set', project: 'alpha', subject: 'alice', roles: ['reader'] });
  await assert.rejects(call(alice, 'proposals'), /denied/, 'reader-only membership cannot inspect pending proposals');
  await assert.rejects(call(alice, 'proposal-show', { proposal_id: stale.id }), /denied/);
  await store.admin({ operation: 'member-set', project: 'alpha', subject: 'alice', roles: ['reader', 'contributor', 'reviewer'] });
  await store.admin({ operation: 'member-set', project: 'alpha', subject: 'admin', roles: ['maintainer'] });
  await assert.rejects(call(bob, 'review', { ...review, proposal_id: stale.id, confirm: stale.digest }), /conflict/);
  const atomic = await call(alice, 'propose', { ...input, request_id: randomUUID(), key: 'decisions/atomic' });
  const probe = new DatabaseSync(join(base, 'team', 'team.db'));
  probe.exec(`CREATE TRIGGER fail_review_audit BEFORE INSERT ON team_audit WHEN json_extract(NEW.value,'$.operation')='review' AND json_extract(NEW.value,'$.result')='accepted' BEGIN SELECT RAISE(ABORT,'injected failure'); END;`);
  await assert.rejects(call(bob, 'review', { ...review, proposal_id: atomic.id, confirm: atomic.digest }));
  probe.exec('DROP TRIGGER fail_review_audit');
  assert.equal(await call(bob, 'read', { key: 'decisions/atomic' }), null, 'audit failure rolls back revision/head/review');
  await call(bob, 'review', { ...review, proposal_id: atomic.id, confirm: atomic.digest });
  probe.close();
  const child = spawn(process.execPath, ['--input-type=module', '-e', `import{openTeamStore}from './dist/team-store.js';const s=await openTeamStore(process.argv[1]);await s.admin({operation:'member-set',project:'alpha',subject:'alice',roles:[]});await s.close();`, join(base, 'team')], { env: { ...process.env, CAIRN_TEAM: '1' }, stdio: ['ignore', 'pipe', 'pipe'] });
  let stderr = ''; child.stderr.on('data', chunk => stderr += chunk);
  assert.equal(await new Promise(resolve => child.on('exit', resolve)), 0, stderr);
  await assert.rejects(call(alice, 'list'), /denied/, 'other process membership update takes effect on existing connection');
  const audit = await call(auditor, 'audit');
  assert.equal(JSON.stringify(audit).includes(value), false, 'audit has no memory values');
  assert.equal(JSON.stringify(audit).includes(alice), false, 'audit has no credentials');
  assert.ok(audit.some(x => x.result === 'denied'));
  assert.ok(audit.some(x => x.operation === 'review' && x.result === 'accepted'));
  console.log('ok: immutable proposals, explicit selection, human review, digest/policy/base conflicts, scoped retrieval and private audit');
} finally { await store.close(); rmSync(base, { recursive: true, force: true }); }
