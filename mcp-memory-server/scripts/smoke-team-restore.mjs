import assert from 'node:assert/strict';
import { hardenPrivatePath } from '../dist/platform-security.js';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import { openTeamStore, teamDigest, verifyTeamSnapshot, restoreTeamSnapshot } from '../dist/team-store.js';

process.env.CAIRN_TEAM = '1';
const base = mkdtempSync(join(tmpdir(), 'cairn-team-restore-'));
hardenPrivatePath(base);
const store = await openTeamStore(join(base, 'source'), { create: true, organization: 'demo-org' });
let restored;
try {
  await store.admin({ operation: 'project-create', project: 'alpha' });
  await store.admin({ operation: 'member-set', project: 'alpha', subject: 'alice', roles: ['reader', 'contributor'] });
  await store.admin({ operation: 'member-set', project: 'alpha', subject: 'bob', roles: ['reviewer'] });
  const issue = (s, subject) => s.issue({ subject, credential_class: 'human', expires_at: new Date(Date.now() + 60000).toISOString() });
  const alice = await issue(store, 'alice'), bob = await issue(store, 'bob');
  const call = (s, token, operation, extra = {}) => s.execute(token, { organization: 'demo-org', project: 'alpha', operation, ...extra });
  const value = 'Preserve reviewed context across harnesses.';
  const proposal = await call(store, alice.token, 'propose', { request_id: randomUUID(), key: 'decisions/continuity', value, confirm: teamDigest(value), source_scope: 'selected-local', source_digest: teamDigest('selected fixture'), expires_at: new Date(Date.now() + 60000).toISOString(), base_revision: null });
  await call(store, bob.token, 'review', { proposal_id: proposal.id, confirm: proposal.digest, decision: 'approve' });
  const snapshot = await store.snapshot();
  assert.equal(verifyTeamSnapshot(snapshot).digest, snapshot.digest);
  assert.equal(JSON.stringify(snapshot).includes(alice.token), false);
  const corrupt = structuredClone(snapshot); corrupt.records.find(x => x.kind === 'revision').value.value = 'tampered';
  await assert.rejects(restoreTeamSnapshot(join(base, 'corrupt'), corrupt, snapshot.digest));
  assert.throws(() => verifyTeamSnapshot({ ...snapshot, unknown: true }));
  const brokenReference = structuredClone(snapshot);
  brokenReference.records = brokenReference.records.filter(row => row.kind !== 'review');
  const { digest: _digest, ...brokenBody } = brokenReference;
  brokenReference.digest = teamDigest(JSON.stringify(brokenBody));
  assert.throws(() => verifyTeamSnapshot(brokenReference), /integrity/, 'rehashed snapshot cannot orphan an approved revision');
  await assert.rejects(restoreTeamSnapshot(join(base, 'source'), snapshot, snapshot.digest), /conflict/);
  if (process.platform !== 'win32') {
    symlinkSync(join(base, 'source'), join(base, 'linked-source'));
    await assert.rejects(openTeamStore(join(base, 'linked-source')), /integrity/);
    symlinkSync(join(base, 'missing'), join(base, 'dangling-target'));
    await assert.rejects(restoreTeamSnapshot(join(base, 'dangling-target'), snapshot, snapshot.digest), /conflict/);
  }
  await assert.rejects(restoreTeamSnapshot(join(base, 'wrong-digest'), snapshot, '0'.repeat(64)), /conflict/);
  const interrupted = restoreTeamSnapshot(join(base, 'competing-target'), snapshot, snapshot.digest);
  mkdirSync(join(base, 'competing-target'), { mode: 0o700 });
  writeFileSync(join(base, 'competing-target', 'sentinel'), 'preserve competing target');
  await assert.rejects(interrupted, /conflict/);
  assert.equal(readFileSync(join(base, 'competing-target', 'sentinel'), 'utf8'), 'preserve competing target');
  assert.equal(existsSync(join(base, 'competing-target', 'team.db')), false, 'failed publication leaves no partial enabled store');
  assert.equal(existsSync(join(base, '.competing-target.restore.lock')), false);
  assert.deepEqual(readdirSync(base).filter(name => name.startsWith('.team-restore-')), [], 'failed restore cleans only its generated temporary');
  const concurrent = await Promise.allSettled([restoreTeamSnapshot(join(base, 'concurrent'), snapshot, snapshot.digest), restoreTeamSnapshot(join(base, 'concurrent'), snapshot, snapshot.digest)]);
  assert.equal(concurrent.filter(x => x.status === 'fulfilled').length, 1);
  await concurrent.find(x => x.status === 'fulfilled').value.close();
  assert.equal(existsSync(join(base, '.concurrent.restore.lock')), false);
  restored = await restoreTeamSnapshot(join(base, 'restored'), snapshot, snapshot.digest);
  await assert.rejects(call(restored, alice.token, 'list'), /unauthorized/, 'restore must not reactivate old credentials');
  const fresh = await issue(restored, 'alice');
  assert.equal((await call(restored, fresh.token, 'read', { key: 'decisions/continuity' })).value, value);
  assert.equal((await restored.doctor()).ok, true);
  mkdirSync(join(base, '.team-restore-interrupted'), { mode: 0o700 });
  assert.equal((await restored.doctor()).temporary_remnants, 1);
  assert.equal(existsSync(join(base, '.team-restore-interrupted')), true, 'doctor must not discard a possible recovery artifact');
  const active = await call(store, alice.token, 'read', { key: 'decisions/continuity' });
  await store.admin({ operation: 'memory-delete', project: 'alpha', key: 'decisions/continuity', confirm: active.provenance.revision_digest });
  assert.equal(await call(store, alice.token, 'read', { key: 'decisions/continuity' }), null);
  assert.deepEqual(await call(store, alice.token, 'history', { key: 'decisions/continuity' }), []);
  assert.equal(JSON.stringify(await store.snapshot()).includes(value), false, 'explicit deletion removes selected content from current store');
  const probe = new DatabaseSync(join(base, 'restored', 'team.db'));
  probe.exec("UPDATE team_audit SET digest='0000' WHERE sequence=1"); probe.close();
  await assert.rejects(restored.doctor(), /integrity/);
  writeFileSync(join(base, 'not-directory'), 'bad');
  await assert.rejects(openTeamStore(join(base, 'not-directory')), /integrity/);
  console.log('ok: verified consistent snapshot, digest/audit tampering, fresh-only restore, revoked restored credentials, explicit deletion and private-path safety');
} finally { await restored?.close(); await store.close(); rmSync(base, { recursive: true, force: true }); }
