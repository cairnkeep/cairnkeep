import assert from 'node:assert/strict';
import { rankHybridMemory } from '../dist/memory-retrieval.js';

const entry = (key, value, scope = 'project') => ({ scope, key, value });
const target = entry('decisions/office-tunnel', 'Office tunnel access uses gateway ember-42. Aliases: relaybox, relay box.');
const noise = Array.from({ length: 128 }, (_, i) => entry(`patterns/noise-${i}`, `Office release checklist ${i}. Archive unrelated deployment logs.`));
const entries = [target, ...noise];
const search = (query, options = {}) => rankHybridMemory(entries, query, { topK: 8, minScore: 0, ...options });
assert.equal(search('office tunnel access').results[0].key, target.key);
assert.equal(search('cooking sourdough bread').results.length, 0);
assert.equal(search('cooking sourdough bread').retrieval.empty_reason, 'no_relevant_memory');
assert.equal(search('ember-43 gateway').results.length, 0, 'nearby identifiers must not match');
const addresses = [entry('decisions/gateway-address', 'The gateway address is 192.0.2.10; firmware version 4.2.1.')];
assert.equal(rankHybridMemory(addresses, '192.0.2.11', { topK: 5, minScore: 0 }).results.length, 0);
assert.equal(rankHybridMemory(addresses, '192.0.2.10', { topK: 5, minScore: 0 }).results.length, 1);
assert.equal(rankHybridMemory(addresses, 'firmware 4.2.2', { topK: 5, minScore: 0 }).results.length, 0);
assert.equal(search('relaybox').results[0].key, target.key, 'aliases curated into ordinary text remain searchable');
assert.equal(search('home connection', { aliases: ['office tunnel access'] }).results[0].key, target.key);
assert.equal(search('cooking sourdough bread', { semanticScores: new Map(entries.map(item => [item, 0.2])) }).results.length, 0, 'weak positive cosines cannot fill the result budget');
assert.equal(search('remote connectivity', { semanticScores: new Map([[target, 0.9]]), minScore: 0.8 }).results[0].key, target.key);
assert.equal(search('ember-43 gateway', { semanticScores: new Map([[target, 0.99]]), minScore: 0.8 }).results.length, 0, 'semantic scores cannot override an explicit identifier mismatch');
assert.equal(search('remote connectivity', { semanticScores: new Map([[target, NaN]]), minScore: 0.8 }).results.length, 0);
assert.deepEqual(search('office tunnel access').results, search('office tunnel access').results, 'ties and output are deterministic');
const duplicate = entry(target.key, target.value, 'identity');
const conflicting = entry(target.key, 'Office tunnel access uses gateway frost-99.', 'work');
const conflicts = rankHybridMemory([target, duplicate, conflicting], 'office tunnel access', { topK: 8, minScore: 0, explain: true });
assert.equal(conflicts.results.length, 2, 'only identical key/value pairs collapse');
assert.equal(conflicts.results.find(item => item.value === target.value).match.sources.length, 2);
assert.equal(conflicts.retrieval.possible_conflicts.length, 1, 'different live values are surfaced, never automatically reconciled');
assert.ok(conflicts.results.every(item => item.match.reasons.length));
assert.equal(search('office tunnel access').results[0].match, undefined, 'explanations are explicit');
assert.throws(() => search('x'.repeat(4097)), /bounded/);
assert.throws(() => search('office', { aliases: Array(9).fill('alias') }), /bounded/);
assert.throws(() => search('office', { minScore: NaN }), /bounded/);
console.log('PASS: hybrid identifier/lexical/semantic admission, aliases, empty results, deterministic ranking and duplicate/conflict explanations');
